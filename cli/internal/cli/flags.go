package cli

import (
	"fmt"
	"io"
	"strings"
)

// stringList implements flag.Value for repeatable filters such as
// --schema. Each occurrence may itself contain a comma-separated list.
type stringList []string

// String is used by flag's help output, not for parsing.
func (s *stringList) String() string {
	return strings.Join(*s, ",")
}

// Set appends all non-empty comma-separated parts. Empty values are ignored
// so accidental trailing commas do not create a filter for the empty string.
func (s *stringList) Set(value string) error {
	for _, part := range strings.Split(value, ",") {
		part = strings.TrimSpace(part)
		if part != "" {
			*s = append(*s, part)
		}
	}
	return nil
}

func parseKind(value string) (string, error) {
	switch value {
	case "logical", "physical":
		return value, nil
	default:
		return "", fmt.Errorf("invalid --kind %q (want logical or physical)", value)
	}
}

func parseFormat(value string) (string, error) {
	switch value {
	case "text", "json":
		return value, nil
	default:
		return "", fmt.Errorf("invalid --format %q (want text or json)", value)
	}
}

func parseFailOn(value string) (string, error) {
	switch value {
	case "changed", "new", "missing", "any", "none":
		return value, nil
	default:
		return "", fmt.Errorf("invalid --fail-on %q", value)
	}
}

// usage is the top-level help text. Command-specific help is generated by
// each flag set.
func usage(w io.Writer) {
	text := "pg_integrity_checksums - baseline and verification tool\n" +
		"\n" +
		"Usage:\n" +
		"  pg_integrity_checksums capture [options]\n" +
		"  pg_integrity_checksums verify  [options]\n" +
		"  pg_integrity_checksums diff    OLD.json NEW.json [options]\n" +
		"  pg_integrity_checksums show    FILE [options]\n" +
		"  pg_integrity_checksums update  [options]\n" +
		"  pg_integrity_checksums doctor  [options]\n" +
		"  pg_integrity_checksums version\n" +
		"\n" +
		"Run pg_integrity_checksums <command> --help for command flags.\n" +
		"\n" +
		"Connection:\n" +
		"  --db accepts a PostgreSQL connection string. If omitted, DATABASE_URL\n" +
		"  is used, followed by the standard PG* environment variables.\n" +
		"\n" +
		"Exit codes:\n" +
		"  0 success\n" +
		"  1 differences found\n" +
		"  2 operational error\n" +
		"  3 invalid baseline / incompatible version\n" +
		"  4 destructive operation refused\n"
	fmt.Fprint(w, text)
}

// commandError prints an operational error and returns exit code 2.
func commandError(stderr io.Writer, err error) int {
	if err == nil {
		return 0
	}
	fmt.Fprintf(stderr, "error: %v\n", err)
	return 2
}
