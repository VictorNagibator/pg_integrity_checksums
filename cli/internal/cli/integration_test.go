func TestIntegrationCaptureVerifyUpdate(t *testing.T) {
	dsn := os.Getenv("PGICS_TEST_DSN")
	if dsn == "" {
		t.Skip("PGICS_TEST_DSN is not set")
	}
	ctx := context.Background()
	db, err := pgdb.Open(ctx, dsn)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()

	schema := fmt.Sprintf("pgics_it_%d", time.Now().UnixNano())
	if _, err := db.ExecContext(ctx, "CREATE SCHEMA "+schema); err != nil {
		t.Fatal(err)
	}
	defer db.ExecContext(ctx, "DROP SCHEMA "+schema+" CASCADE")

	_, err = db.ExecContext(ctx, "CREATE TABLE "+schema+".accounts (id int PRIMARY KEY, name text, amount numeric(12,2))")
	if err != nil {
		t.Fatal(err)
	}
	if _, err := db.ExecContext(ctx, "INSERT INTO "+schema+".accounts VALUES (1,'a',1.00),(2,'b',2.00)"); err != nil {
		t.Fatal(err)
	}
	if _, err := db.ExecContext(ctx, "CREATE INDEX accounts_name_idx ON "+schema+".accounts(name)"); err != nil {
		t.Fatal(err)
	}

	path := filepath.Join(t.TempDir(), "baseline.json")
	code, _, errOut := runCLI("capture", "--db", dsn, "--schema", schema, "--output", path, "--quiet")
	if code != 0 {
		t.Fatalf("capture: code=%d err=%s", code, errOut)
	}

	code, _, errOut = runCLI("verify", "--db", dsn, "--baseline", path, "--quiet")
	if code != 0 {
		t.Fatalf("verify clean: code=%d err=%s", code, errOut)
	}

	if _, err := db.ExecContext(ctx, "UPDATE "+schema+".accounts SET amount = amount + 1 WHERE id = 1"); err != nil {
		t.Fatal(err)
	}
	code, _, errOut = runCLI("verify", "--db", dsn, "--baseline", path, "--quiet")
	if code != 1 {
		t.Fatalf("verify changed: code=%d err=%s", code, errOut)
	}

	code, _, errOut = runCLI("update", "--db", dsn, "--baseline", path, "--yes", "--quiet")
	if code != 0 {
		t.Fatalf("update: code=%d err=%s", code, errOut)
	}
	code, _, errOut = runCLI("verify", "--db", dsn, "--baseline", path, "--quiet")
	if code != 0 {
		t.Fatalf("verify after update: code=%d err=%s", code, errOut)
	}

	physicalPath := filepath.Join(t.TempDir(), "physical.json")
	code, _, errOut = runCLI("capture", "--db", dsn, "--schema", schema, "--kind", "physical", "--output", physicalPath, "--quiet")
	if code != 0 {
		t.Fatalf("physical capture: code=%d err=%s", code, errOut)
	}
	code, _, errOut = runCLI("verify", "--db", dsn, "--baseline", physicalPath, "--quiet")
	if code != 0 {
		t.Fatalf("physical verify: code=%d err=%s", code, errOut)
	}
}

func TestIntegrationSequences(t *testing.T) {
	dsn := os.Getenv("PGICS_TEST_DSN")
	if dsn == "" {
		t.Skip("PGICS_TEST_DSN is not set")
	}
	ctx := context.Background()
	db, err := pgdb.Open(ctx, dsn)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()

	schema := fmt.Sprintf("pgics_seq_%d", time.Now().UnixNano())
	for _, stmt := range []string{
		"CREATE SCHEMA " + schema,
		"CREATE TABLE " + schema + ".orders (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v text)",
		"INSERT INTO " + schema + ".orders (v) VALUES ('a'), ('b')",
		"CREATE SEQUENCE " + schema + ".invoice_no",
	} {
		if _, err := db.ExecContext(ctx, stmt); err != nil {
			t.Fatal(err)
		}
	}
	defer db.ExecContext(ctx, "DROP SCHEMA "+schema+" CASCADE")

	path := filepath.Join(t.TempDir(), "baseline.json")
	code, _, errOut := runCLI("capture", "--db", dsn, "--schema", schema, "--output", path, "--quiet")
	if code != 0 {
		t.Fatalf("capture: code=%d err=%s", code, errOut)
	}
	b, err := baseline.Load(path)
	if err != nil {
		t.Fatal(err)
	}
	if !b.Scope.IncludeSequences {
		t.Fatal("scope does not include sequences")
	}
	var owned, free bool
	for _, o := range b.Objects {
		if o.Kind != baseline.ObjectSequence {
			continue
		}
		switch o.Name {
		case "orders_id_seq":
			owned = o.TableName == "orders" && o.Status == baseline.StatusOK
		case "invoice_no":
			free = o.TableName == "" && o.Status == baseline.StatusOK
		}
	}
	if !owned || !free {
		t.Fatalf("sequences missing from baseline: %+v", b.Objects)
	}

	code, _, errOut = runCLI("verify", "--db", dsn, "--baseline", path, "--quiet")
	if code != 0 {
		t.Fatalf("verify clean: code=%d err=%s", code, errOut)
	}

	// doctor lists sequences with their privilege check.
	code, out, errOut := runCLI("doctor", "--db", dsn, "--format", "json", "--verbose", "--quiet")
	if code != 0 || !strings.Contains(out, `"sequence"`) || !strings.Contains(out, `"invoice_no"`) {
		t.Fatalf("doctor: code=%d out=%s err=%s", code, out, errOut)
	}

	// A sequence that moved while the table rows did not is a change: after
	// a migration it would hand out duplicate keys.
	if _, err := db.ExecContext(ctx, "SELECT nextval('"+schema+".invoice_no')"); err != nil {
		t.Fatal(err)
	}
	code, out, errOut = runCLI("verify", "--db", dsn, "--baseline", path, "--format", "json")
	if code != 1 {
		t.Fatalf("verify after nextval: code=%d out=%s err=%s", code, out, errOut)
	}
	if !strings.Contains(out, `"invoice_no"`) {
		t.Fatalf("verify does not report the sequence: %s", out)
	}
	if _, err := db.ExecContext(ctx, "SELECT setval('"+schema+".invoice_no', 1, false)"); err != nil {
		t.Fatal(err)
	}
	code, _, errOut = runCLI("verify", "--db", dsn, "--baseline", path, "--quiet")
	if code != 0 {
		t.Fatalf("verify after restoring the sequence: code=%d err=%s", code, errOut)
	}

	// A definition change is a schema change.
	if _, err := db.ExecContext(ctx, "ALTER SEQUENCE "+schema+".invoice_no INCREMENT 10"); err != nil {
		t.Fatal(err)
	}
	code, out, _ = runCLI("verify", "--db", dsn, "--baseline", path, "--format", "json")
	if code != 1 || !strings.Contains(out, `"schema_changed": 1`) {
		t.Fatalf("verify after ALTER SEQUENCE: code=%d out=%s", code, out)
	}

	// --no-sequences leaves them out, and verify honours the stored scope.
	noSeq := filepath.Join(t.TempDir(), "noseq.json")
	code, _, errOut = runCLI("capture", "--db", dsn, "--schema", schema, "--no-sequences", "--output", noSeq, "--quiet")
	if code != 0 {
		t.Fatalf("capture --no-sequences: code=%d err=%s", code, errOut)
	}
	nb, err := baseline.Load(noSeq)
	if err != nil {
		t.Fatal(err)
	}
	for _, o := range nb.Objects {
		if o.Kind == baseline.ObjectSequence {
			t.Fatalf("--no-sequences captured %s", o.Identity())
		}
	}
	if _, err := db.ExecContext(ctx, "SELECT nextval('"+schema+".invoice_no')"); err != nil {
		t.Fatal(err)
	}
	code, _, errOut = runCLI("verify", "--db", dsn, "--baseline", noSeq, "--quiet")
	if code != 0 {
		t.Fatalf("verify without sequences: code=%d err=%s", code, errOut)
	}

	// Physical baselines have no sequences.
	phys := filepath.Join(t.TempDir(), "physical.json")
	code, _, errOut = runCLI("capture", "--db", dsn, "--schema", schema, "--kind", "physical", "--output", phys, "--quiet")
	if code != 0 {
		t.Fatalf("physical capture: code=%d err=%s", code, errOut)
	}
	pb, err := baseline.Load(phys)
	if err != nil {
		t.Fatal(err)
	}
	if pb.Scope.IncludeSequences {
		t.Fatal("physical scope includes sequences")
	}
}

// TestIntegrationSequencesOldExtension checks capture and verify against an
// extension that predates pg_sequence_logical_checksum (2.8.0).
func TestIntegrationSequencesOldExtension(t *testing.T) {
	dsn := os.Getenv("PGICS_TEST_DSN")
	if dsn == "" {
		t.Skip("PGICS_TEST_DSN is not set")
	}
	ctx := context.Background()
	admin, err := pgdb.Open(ctx, dsn)
	if err != nil {
		t.Fatal(err)
	}
	defer admin.Close()

	dbname := fmt.Sprintf("pgics_oldext_%d", time.Now().UnixNano())
	if _, err := admin.ExecContext(ctx, "CREATE DATABASE "+dbname); err != nil {
		t.Skipf("cannot create a second database: %v", err)
	}
	defer admin.ExecContext(ctx, "DROP DATABASE "+dbname)

	cfg, err := pgx.ParseConfig(dsn)
	if err != nil {
		t.Fatal(err)
	}
	cfg.Database = dbname
	oldDSN := stdlib.RegisterConnConfig(cfg)
	defer stdlib.UnregisterConnConfig(oldDSN)
	old, err := pgdb.Open(ctx, oldDSN)
	if err != nil {
		t.Fatal(err)
	}
	defer old.Close()
	for _, stmt := range []string{
		"CREATE EXTENSION pg_integrity_checksums VERSION '2.8.0'",
		"CREATE TABLE t (id serial PRIMARY KEY)",
		"CREATE SEQUENCE s",
	} {
		if _, err := old.ExecContext(ctx, stmt); err != nil {
			t.Skipf("cannot set up extension 2.8.0: %v", err)
		}
	}
	cliDSN := oldDSN

	// Default capture: warns and leaves sequences out.
	path := filepath.Join(t.TempDir(), "old.json")
	code, _, errOut := runCLI("capture", "--db", cliDSN, "--output", path)
	if code != 0 || !strings.Contains(errOut, "cannot checksum sequences") {
		t.Fatalf("capture: code=%d err=%s", code, errOut)
	}
	b, err := baseline.Load(path)
	if err != nil {
		t.Fatal(err)
	}
	if b.Scope.IncludeSequences {
		t.Fatal("scope includes sequences without extension support")
	}
	code, _, errOut = runCLI("verify", "--db", cliDSN, "--baseline", path, "--quiet")
	if code != 0 {
		t.Fatalf("verify: code=%d err=%s", code, errOut)
	}

	// An explicit request fails.
	code, _, errOut = runCLI("capture", "--db", cliDSN, "--no-sequences=false",
		"--output", filepath.Join(t.TempDir(), "x.json"), "--quiet")
	if code == 0 || !strings.Contains(errOut, "needs 2.9.0") {
		t.Fatalf("explicit capture: code=%d err=%s", code, errOut)
	}
}
